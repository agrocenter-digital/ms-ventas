package com.agrocenter.ms_ventas.messaging.outbox;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

@Entity
@Table(name = "outbox_eventos")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class OutboxEvent {
    @Id @Column(name = "event_id", length = 36) private String eventId;
    @Column(name = "orden", nullable = false, insertable = false, updatable = false,
            columnDefinition = "bigint generated by default as identity") private Long orden;
    @Column(name = "event_type", nullable = false, length = 100) private String eventType;
    @Column(name = "aggregate_id", nullable = false, length = 100) private String aggregateId;
    @Column(name = "partition_key", nullable = false, length = 256) private String partitionKey;
    @Column(nullable = false, columnDefinition = "TEXT") private String payload;
    @Column(name = "created_at", nullable = false) private Instant createdAt;
    @Column(name = "sent_at") private Instant sentAt;
    @Column(nullable = false) private int attempts;
    @Column(name = "next_attempt_at", nullable = false) private Instant nextAttemptAt;
    @Column(name = "last_error", length = 1000) private String lastError;

    public OutboxEvent(String eventId, String eventType, String aggregateId, String partitionKey, String payload, Instant now) {
        this.eventId = eventId;
        this.eventType = eventType;
        this.aggregateId = aggregateId;
        this.partitionKey = partitionKey;
        this.payload = payload;
        this.createdAt = now;
        this.nextAttemptAt = now;
    }

    public void enviado(Instant now) { sentAt = now; lastError = null; }
    public void fallido(Instant now, String error) {
        attempts++;
        nextAttemptAt = now.plusSeconds(Math.min(300, 1L << Math.min(attempts, 8)));
        lastError = error == null ? "Error de publicacion" : error.substring(0, Math.min(1000, error.length()));
    }
}
